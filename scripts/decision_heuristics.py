def get_heuristic(canonical: str) -> dict:
    """返回某 canonical 主题的决策卡；未知主题返回空卡（不抛错，便于容错）。"""
    return DECISION_HEURISTICS.get(canonical, {})


def heuristics_for_topics(topics) -> list:
    """给定一组方法论主题，返回对应的决策卡列表（保持主题顺序）。

    自动附带该主题的基准动作方向 recommended_direction（buy/hold/avoid），
    使召回切片直接呈现"可下注的决策指令"（决策型认知 RAG 的核心）。
    """
    cards = []
    for t in topics or []:
        card = DECISION_HEURISTICS.get(t)
        if card:
            cards.append({"canonical": t, "recommended_direction": DECISION_DIRECTION.get(t, "hold"), **card})
    return cards


def all_canonicals() -> list:
    return list(DECISION_HEURISTICS.keys())
