# ---------------------------------------------------------------------------
# 反向索引：任意学名 / 现象词 -> canonical
# ---------------------------------------------------------------------------
TERM_TO_CANONICAL = {}
for canonical, terms in METHODOLOGY_ALIASES.items():
    for t in terms:
        TERM_TO_CANONICAL[t.lower()] = canonical

PHENOMENON_TO_CANONICAL = {}
for canonical, ph in METHODOLOGY_PHENOMENA.items():
    for p in ph:
        PHENOMENON_TO_CANONICAL[p.lower()] = canonical


def canonical_for_term(term: str):
    """给定一个学名/现象词，返回其规范方法论主题名；未命中返回 None。"""
    key = term.lower().strip()
    return TERM_TO_CANONICAL.get(key) or PHENOMENON_TO_CANONICAL.get(key)


# 向后兼容：早期版本叫 ALIAS_TO_CANONICAL（仅学名层）。
ALIAS_TO_CANONICAL = dict(TERM_TO_CANONICAL)


def canonical_for_text(text: str) -> dict:
    """给定一段文本（用户提问 / 切片），返回命中的方法论主题。

    同时查 Level 1 学名与 Level 2 现象词袋，解决"专有名词断裂"：
    用户描述现象（泡沫破裂/路网留下）也能归一到佩蕾丝技术资本周期。

    返回 {"canonical_topics": [...按命中数降序], "hit_terms": {canonical: [命中的词]}}
    """
    low = text.lower()
    hits = {}
    for term, canonical in TERM_TO_CANONICAL.items():
        if term and term in low:
            hits.setdefault(canonical, []).append(term)
    for ph, canonical in PHENOMENON_TO_CANONICAL.items():
        if ph and ph in low:
            hits.setdefault(canonical, []).append(ph)
    ordered = sorted(hits.items(), key=lambda kv: -len(kv[1]))
    return {"canonical_topics": [c for c, _ in ordered], "hit_terms": {c: w for c, w in ordered}}
